"""
Scans benchmark/results/*.json and generates results_manifest.js
so viewer.html can load all runs without manual file upload.

Usage:  python benchmark/build_viewer.py
        (run from project root, or from benchmark/ directory)
"""

import json
import glob
import os

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
RESULTS_DIR = os.path.join(SCRIPT_DIR, "results")
OUTPUT_FILE = os.path.join(SCRIPT_DIR, "results_manifest.js")


def main():
    json_files = sorted(glob.glob(os.path.join(RESULTS_DIR, "*.json")))

    runs = []
    for path in json_files:
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            runs.append(data)
        except (json.JSONDecodeError, OSError) as e:
            print(f"  Skipping {os.path.basename(path)}: {e}")

    js_content = f"// Auto-generated by build_viewer.py — do not edit\nwindow.__BENCHMARK_RUNS__ = {json.dumps(runs, separators=(',', ':'))};\n"

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"Built {OUTPUT_FILE} with {len(runs)} run(s)")


if __name__ == "__main__":
    main()
